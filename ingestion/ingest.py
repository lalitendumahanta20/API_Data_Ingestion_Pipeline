# Rad Page limit from env
PAGE_LIMIT=int(os.getenv("API_PAGE_LIMIT","2"))

# Step 1 - Save Original API Response

def save_raw_response(cursor,run_id,endpoint,page,response):
    response_json=response.text
    
    # Check the response contain valid json
    json.loads(response_json)
    request_params=json.dumps({
        "page":page,
        "limit":PAGE_LIMIT
    })
    
    cursor.execute(
        """
        insert into raw_api_responses (run_id,endpoint,page_number,http_status,request_params,response_json)
        output INSERTED.response_id
        values(?,?,?,?,?,?)
        """,
        run_id,endpoint,page,response.status_code,request_params,response_json
    )
    
    # Get The id generated by SQL Server
    response_id=cursor.fetchone()[0]
    
    return response_id

# Create the quartine records
def quarantine_record(cursor,run_id,response_id,entity_type,record,errors):
    # Convert original record into JSON
    original_json=json.dumps(record)
    
    # Combine all validation errors
    error_reason=";".join(errors)
    
    cursor.execute(
        """
        insert into rejected_records(run_id,response_id,entity_type,original_record_json,error_reason)
        values(?,?,?,?,?)
        """,
        run_id,response_id,entity_type,original_json,error_reason 
    )
    print(f"Rejected {entity_type}: {error_reason}")
    
# Insert Customer Data
def insert_customers(cursor,records):
    inserted_count=0
    updated_count=0
    
    for record in records:
        customer_id=record["customer_id"]
        cursor.execute(
            """
            select 1 from customers
            where customer_id= ?
            """,
            customer_id
        )
        
        existing_customer=cursor.fetchone()
        
        if existing_customer is None:
            cursor.execute(
                """
                insert into customers
                (
                    customer_id,customer_name,email,source_created_at,source_updated_at
                )
                values (
                    ?,?,?,convert(datetimeoffset,?),convert(datetimeoffset,?)
                )
                """,
                record["customer_id"],
                record["customer_name"],
                record["email"],
                record["created_at"],
                record["updated_at"]
            )
            
            inserted_count += 1
        
        else:
            cursor.execute(
                """
                update customers
                set
                    customer_name=?,
                    email=?,
                    source_updated_at = convert(datetimeoffset,?),
                    modified_at = SYSUTCDATETIME()
                where customer_id = ?
                and source_updated_at < CONVERT(datetimeoffset, ?)
                """,
                    record["customer_name"],
                    record["email"],
                    record["updated_at"],
                    customer_id,
                    record["updated_at"]
            )
            
            if cursor.rowcount > 0:
                updated_count += 1
                
    return inserted_count, updated_count
    

