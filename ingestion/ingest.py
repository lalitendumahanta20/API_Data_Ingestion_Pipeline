# read the previous successful checkpoints
def get_checkpoint(cursor,entity_name):
    cursor.execute(
        """
        select convert(varchar(50),last_successful_updated_at,127)
        from checkpoints
        where entity_name=?
        """,
        entity_name
    )
    result=cursor.fetchone()
    
    if result is None:
        return datetime(1970, 1, 1, tzinfo=timezone.utc)
    
    checkpoint_string=result[0]
    
    checkpoint = datetime.fromisoformat(
        checkpoint_string.replace("Z", "+00:00")
    )
    
    if checkpoint.tzinfo is None:
        checkpoint = checkpoint.replace(tzinfo=timezone.utc)
    
    return checkpoint

# Convert the checkpoint into API format
def format_checkpoint(checkpoint):

    if checkpoint.tzinfo is None:
        checkpoint = checkpoint.replace(tzinfo=timezone.utc)

    return checkpoint.isoformat().replace("+00:00", "Z")

# Save the new checkpoint
def save_checkpoint(cursor, entity_name, checkpoint, run_id):

    cursor.execute(
        """
        SELECT entity_name
        FROM dbo.checkpoints
        WHERE entity_name = ?
        """,
        entity_name
    )

    existing = cursor.fetchone()

    if existing:

        cursor.execute(
            """
            UPDATE dbo.checkpoints
            SET last_successful_updated_at = ?,
                last_run_id = ?,
                updated_at = SYSUTCDATETIME()
            WHERE entity_name = ?
            """,
            checkpoint,
            run_id,
            entity_name
        )

    else:

        cursor.execute(
            """
            INSERT INTO dbo.checkpoints
            (
                entity_name,
                last_successful_updated_at,
                last_run_id,
                updated_at
            )
            VALUES (?, ?, ?, SYSUTCDATETIME())
            """,
            entity_name,
            checkpoint,
            run_id
        )
        

# Step 4 - Fetch all pages from an API Endpoint
def ingest_endpoint(cursor,connection,run_id,endpoint,insert_function,checkpoint):
    page=1
    
    total_fetched=0
    total_inserted=0
    total_rejected=0
    total_updated = 0
    max_updated_at = checkpoint
    
    logger.info("Starting ingestion for endpoint: %s", endpoint)
    
    while True:
        print(f"fetching {endpoint} - page {page}")
        
        # Enable simulated failure only when testing
        test_fail_first=(
            os.getenv("API_TEST_FAIL_FIRST", "false").lower() == "true"
        )
        
        extra_params={
            "updated_since":format_checkpoint(checkpoint)
        }
        
        # Optional failure testing from Step 5
        test_fail_first = (
            os.getenv("API_TEST_FAIL_FIRST", "false").lower()
            == "true"
        )
        
        if endpoint == "orders" and test_fail_first:
            extra_params["fail_first"]="true"
            
        if not extra_params:
            extra_params=None
            
        # Fetch API page with retry mechanism
        response=fetch_page(
            endpoint,page,PAGE_LIMIT,extra_params=extra_params
        )
        
        logger.info(
            "Fetched API page %s for endpoint %s",
            page,
            endpoint
        )
        
        # Save raw response and obtain its ID
        response_id=save_raw_response(
            cursor,
            run_id,
            endpoint,
            page,
            response
        )
        
        # Connection Commit
        connection.commit()
        
        # Stop if API returned an HTTP error
        response.raise_for_status()
        
        # Convert Json respond into python dictionary
        payload=response.json()
        
        # Extract records from response
        records=payload["data"]
        
        # Count fetched records
        total_fetched += len(records)
        
        logger.info(
            "Total records fetched so far for %s: %s",
            endpoint,
            total_fetched
        )
        
        # Process each record separately
        for record in records:
            
            updated_at=record.get("updated_at")
            if updated_at:
                
                record_timestamp=datetime.fromisoformat(
                    updated_at.replace("Z", "+00:00")
                )
                if record_timestamp > max_updated_at:
                    max_updated_at = record_timestamp
            
            if endpoint=="customers":
                errors=validate_customer(record)
            else:
                errors=validate_order(record,cursor)
               
            # Invalid record goes to quarantine 
            if errors:
                quarantine_record(cursor,run_id,response_id,endpoint[:-1],record,errors)
                
                total_rejected += 1
                
                logger.warning(
                    "Rejected record from %s: %s",
                    endpoint,
                    errors
                )
                
            else:
                # Insert records into SQL Server
                inserted,updated= insert_function(
                    cursor,
                    [record]
                )
                        
                total_inserted += inserted
                total_updated += updated
                
                if inserted > 0:
                    logger.info(
                        "Inserted record into %s: %s",
                        endpoint,
                        record
                    )

                if updated > 0:
                    logger.info(
                        "Updated record in %s: %s",
                        endpoint,
                        record
                    )
        
        # Save inserted records
        connection.commit()
        
        print(
            f"Fetched: {len(records)},"
            f"Inserted: {total_inserted}, "
            f"Rejected: {total_rejected},"
            f"Updated_at: {max_updated_at}"
        )
        
        # Stop when there are no more pages
        if not payload["has_next"]:
            break
        
        # Move to next page
        page=payload["next_page"]
        
    return (total_fetched,total_inserted,total_updated,total_rejected,max_updated_at)



# Step 5 : Main Pipeline
def run_pipeline():
    
    connection = None
    cursor = None
    
    # Create unique ID for this pipeline execution
    run_id = str(uuid.uuid4())
    
    total_fetched=0
    total_inserted=0
    total_updated = 0
    total_rejected = 0
    
    logger.info("Pipeline started")
    logger.info("Run ID: %s", run_id)
    
    try:
        
        # Establish database connection
        connection = get_connection()
        cursor = connection.cursor()

        logger.info("Database connection established")
        # Create Pipeline run record
        cursor.execute(
            """
            insert into pipeline_runs(run_id,status)
            values(?,'RUNNING')
            """,
            run_id
        )
        
        connection.commit()
        
        customer_checkpoint=get_checkpoint(cursor,"customers")
        print("Customer checkpoint:", customer_checkpoint)
              
        # First ingest customers
        fetched,inserted,updated,rejected,customer_max_timestamp = ingest_endpoint(
            cursor,connection,run_id,"customers",insert_customers,customer_checkpoint
        )
        
        total_fetched += fetched
        total_inserted += inserted
        total_updated += updated
        total_rejected += rejected
        
        
        # Then ingest order
        order_checkpoint = get_checkpoint(cursor,"orders")
        print("Order checkpoint:",format_checkpoint(order_checkpoint))
        
        # Customers must exist before orders
        fetched,inserted,updated,rejected,order_max_timestamp = ingest_endpoint(
            cursor,connection,run_id,"orders",insert_orders,order_checkpoint
        )
        
        total_fetched += fetched
        total_inserted += inserted
        total_updated += updated
        total_rejected += rejected
        
         # Save checkpoint after customer ingestion succeeds
        save_checkpoint(cursor,"customers",customer_max_timestamp,run_id)
        save_checkpoint(cursor,"orders",order_max_timestamp,run_id)
        
        # Update pipeline run status
        cursor.execute(
            """
            update pipeline_runs
            set
                status='SUCCESS',
                end_time=sysutcdatetime(),
                records_fetched=?,
                records_inserted=?,
                records_updated = ?,
                records_rejected=?
            where run_id=?
            """,
            total_fetched,
            total_inserted,
            total_updated,
            total_rejected,
            run_id
        )
        
        connection.commit()
        
        logger.info("Pipeline completed successfully")
        logger.info("Total records fetched: %s", total_fetched)
        logger.info("Total records inserted: %s", total_inserted)
        logger.info("Total records updated: %s", total_updated)
        logger.info("Total records rejected: %s", total_rejected)
        
    except Exception as error:
        
        # Log the complete error and traceback
        logger.exception("Pipeline execution failed: %s", error)
        
        # Rollback any uncomitted sql changes
        if connection is not None:
            try:
                connection.rollback()
                logger.warning("Database transaction rolled back")
                        
            except Exception:
                logger.exception("Database rollback failed")
        
        
        # Mark Pipeline as Failed
        try:
            cursor.execute(
                
                """
                update pipeline_runs
                set
                    status='FAILED',
                    end_time=sysutcdatetime(),
                    records_fetched=?,
                    records_inserted=?,
                    records_updated = ?,
                    records_rejected=?,
                    error_message=?
                    where run_id=?
                """,
                total_fetched,
                total_inserted,
                total_updated,
                total_rejected,
                str(error),
                run_id
            )
        
            connection.commit()
            logger.error(
                "Pipeline marked as FAILED. Run ID: %s",
                run_id
            )
        except Exception:
            try:
                connection.rollback()
                
            except Exception:
                logger.exception("Rollback after failed status update also failed")
                
            logger.exception(
                "Could not update pipeline_runs with FAILED status"
            )
        else:
            logger.error(
                "Could not record FAILED status because database connection was unavailable"
            )
        
        print("\nPipeline Failed")
        print("Error: ",error)
        
    finally:
        if cursor is not None:
            cursor.close()
            
        if connection is not None:
            connection.close()
        
        print("Database Connection Closed.")
        
# Step 6- Excute Pipeline
if __name__=="__main__":
    
    import time
    
    start_time=time.perf_counter()
    
    run_pipeline()
    end_time=time.perf_counter()
    
    execution_time= end_time - start_time
    
    print("\n========== PERFORMANCE REPORT ==========")
    print(f"Total Execution Time: {execution_time:.2f} seconds")
